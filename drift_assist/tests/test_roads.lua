local R=require("../roads")
local passed=0
local function test(name,fn) fn();passed+=1;print("PASS "..name) end
local function near(a,b,t) assert(math.abs(a-b)<(t or 1e-4),tostring(a).." ~= "..tostring(b)) end
test("Reads actual minimap wire format, multiple lines, signed / decimal points",function()
    local p=R.parseMinimap("loop|48|0,0;100,0;100,-100;0,-100\nline|30|-10.5,2;50,2\ngarbage", "Circuit")
    assert(#p==2 and p[1].closed and not p[2].closed and p[1].width==48)
    assert(p[1].total>340 and p[1].total<=400)
end)
test("Malformed data and repeated coordinates do not make zero-length segments",function()
    assert(#R.parseMinimap("not a road")==0)
    assert(not R.path("bad",{{x=0,z=0},{x=0,z=0}},false,36))
    local p=R.parseMinimap("line|30|0,0;0,0;0,-100")[1]
    near(p.total,100)
    for i=2,#p.points do assert(p.cum[i]>p.cum[i-1]) end
end)
test("3D race parsing preserves elevation and finite course ends",function()
    local p=assert(R.parseRace("0.0,2.0,0.0;0.0,12.0,-100.0","Race",30))
    assert(not p.closed)
    near(R.point(p,50).y,7)
    local guide=R.guide(p,1,{x=0,y=7,z=-90},20,0,nil)
    near(guide.remaining,10)
end)
test("Loop sampling wraps and reverse direction follows the same road",function()
    local p=R.parseMinimap("loop|40|0,0;100,0;100,-100;0,-100")[1]
    local a=R.point(p,p.total+10)
    local b=R.point(p,10)
    near(a.x,b.x);near(a.z,b.z)
    local _,direction=R.nearest({p},{x=0,z=-50},0)
    assert(direction==-1)
end)
test("Elevation distinguishes overlapping race / overpass paths",function()
    local low=R.parseRace("0,0,0;0,0,-100","Low",30)
    local high=R.parseRace("0,50,0;0,50,-100","High",30)
    local picked=R.nearest({low,high},{x=0,y=52,z=-50},0)
    assert(picked==high)
end)
test("Road distance guard does not authorize an unrelated nearby map",function()
    local p=R.parseMinimap("line|30|0,0;0,-100")[1]
    local g=R.guide(p,1,{x=1000,z=0},30,0,nil)
    assert(g.offRoad)
end)
test("Corner preview slows before a sharp bend",function()
    local p=R.parseMinimap("line|30|0,100;0,0;-100,0")[1]
    local far=R.guide(p,1,{x=0,z=90},50,0,nil)
    local nearCorner=R.guide(p,1,{x=0,z=12},50,0,nil)
    assert(nearCorner.speedLimit<far.speedLimit and nearCorner.curvature>=0)
end)
test("Projection progress avoids jumping across distant sections at intersections",function()
    local p=R.path("cross",{{x=-100,z=0},{x=100,z=0},{x=100,z=300},{x=0,z=300},{x=0,z=-100}},false,30)
    local projected=R.project(p,{x=0,z=0},90,-math.pi/2)
    near(projected.s,100)
end)
test("Reversing a curved path reverses signed curvature",function()
    local pts={}
    for i=0,100 do local a=i/100*math.pi*2;table.insert(pts,{x=100*math.cos(a),z=100*math.sin(a)}) end
    local p=R.path("circle",pts,true,36)
    local a=R.guide(p,1,{x=100,z=0},30,0,nil)
    local b=R.guide(p,-1,{x=100,z=0},30,0,nil)
    assert(a.curvature*b.curvature<0)
end)
print(string.format("Roads: %d scenarios passed",passed))
